const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { resolveTools, mediaToolStatus } = require('../../src/tools/media-tools.cjs');
test('media tools prefer packaged/source binaries and validate explicit configuration', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'flowdm-tools-')); t.after(() => fs.rm(root, { recursive: true, force: true }));
  const bundle = path.join(root, 'media-tools'); await fs.mkdir(bundle);
  const options = { resourcesPath: root, appDir: root, env: {}, platform: 'win32', executablePath: process.execPath };
  assert.equal((await mediaToolStatus(options)).ready, false);
  await fs.writeFile(path.join(bundle, 'yt-dlp.exe'), 'fixture');
  await assert.rejects(resolveTools(options), /ffmpeg/i);
  await fs.writeFile(path.join(bundle, 'ffmpeg.exe'), 'fixture');
  await assert.rejects(resolveTools(options), /aria2c/i);
  await fs.writeFile(path.join(bundle, 'aria2c.exe'), 'fixture');
  const tools = await resolveTools(options); assert.equal(tools.ytDlp, path.join(bundle, 'yt-dlp.exe')); assert.equal(tools.jsRuntime, process.execPath);
  assert.equal((await mediaToolStatus(options)).ready, true);
  const hash = require('node:crypto').createHash('sha256').update('fixture').digest('hex');
  const lockManifest = { entries: { ytDlp: { sha256: hash, bytes: 7 }, ffmpeg: { sha256: hash, bytes: 7 }, aria2c: { sha256: hash, bytes: 7 } } };
  assert.equal((await resolveTools({ ...options, packaged: true, lockManifest })).ffmpeg, tools.ffmpeg);
  await assert.rejects(resolveTools({ ...options, packaged: true, env: { FLOWDM_FFMPEG: tools.ffmpeg } }), /overridden/);
  await assert.rejects(resolveTools({ ...options, packaged: true, lockManifest: { entries: { ...lockManifest.entries, ytDlp: { sha256: 'bad', bytes: 7 } } } }), /integrity/);
  await assert.rejects(resolveTools({ ...options, env: { FLOWDM_YTDLP: 'relative.exe' } }), /absolute/i);
  await assert.rejects(resolveTools({ ...options, env: { FLOWDM_FFMPEG: root } }), /file/i);
  const unix = { ...options, platform: 'linux', resourcesPath: undefined, env: { FLOWDM_YTDLP: path.join(bundle, 'yt-dlp'), FLOWDM_FFMPEG: path.join(bundle, 'ffmpeg'), FLOWDM_ARIA2C: path.join(bundle, 'aria2c') } };
  await fs.writeFile(path.join(bundle, 'yt-dlp'), 'fixture'); await fs.writeFile(path.join(bundle, 'ffmpeg'), 'fixture');
  await fs.writeFile(path.join(bundle, 'aria2c'), 'fixture');
  assert.equal((await resolveTools(unix)).ffmpeg, path.join(bundle, 'ffmpeg'));
  assert.equal((await resolveTools({ ...options, resourcesPath: undefined, env: { PATH: bundle } })).ffmpeg, path.join(bundle, 'ffmpeg.exe'));
  const source = path.join(root, 'vendor', 'media-tools'); await fs.mkdir(source, { recursive: true });
  await fs.copyFile(tools.ytDlp, path.join(source, 'yt-dlp.exe')); await fs.copyFile(tools.ffmpeg, path.join(source, 'ffmpeg.exe'));
  await fs.copyFile(path.join(bundle, 'aria2c.exe'), path.join(source, 'aria2c.exe'));
  assert.equal((await resolveTools({ ...options, resourcesPath: undefined })).ytDlp, path.join(source, 'yt-dlp.exe'));
});
